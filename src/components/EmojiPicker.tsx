const CATEGORY_ICONS: Record<string, string> = {
  'Smileys': '😊',
  'People': '👋',
  'Animals': '🐶',
  'Food': '🍕',
  'Activities': '⚽',
  'Travel': '🚀',
  'Objects': '💡',
  'Symbols': '❤️',
};

interface Props {
  selected: string;
  onSelect: (emoji: string) => void;
}

export default function EmojiPicker({ selected, onSelect }: Props) {
  const [activeCategory, setActiveCategory] = useState('Smileys');
  const [search, setSearch] = useState('');

  const allEmojis = search
    ? Object.values(CATEGORIES).flat().filter(() => true)
    : CATEGORIES[activeCategory] || [];

  return (
    <div>
      {/* Search */}
      <div className="relative mb-3">
        <input
          type="text"
          value={search}
          onChange={(e) => setSearch(e.target.value)}
          placeholder="search or scroll..."
          className="w-full px-4 py-2.5 border-2 border-gray-200 rounded-xl text-sm text-gray-700 placeholder:text-gray-300 focus:border-pink-400 focus:ring-2 focus:ring-pink-100 outline-none transition"
        />
      </div>

      {/* Category tabs */}
      {!search && (
        <div className="flex gap-1 mb-3 overflow-x-auto pb-1 no-scrollbar">
          {Object.keys(CATEGORIES).map((cat) => (
            <button
              key={cat}
              onClick={() => setActiveCategory(cat)}
              className={`flex-shrink-0 px-2.5 py-1.5 rounded-lg text-sm transition-all ${
                activeCategory === cat
                  ? 'bg-pink-100 ring-2 ring-pink-300'
                  : 'bg-gray-100 hover:bg-gray-200'
              }`}
            >
              {CATEGORY_ICONS[cat]}
            </button>
          ))}
        </div>
      )}

      {/* Emoji grid */}
      <div className="grid grid-cols-7 gap-1 max-h-48 overflow-y-auto p-1">
        {allEmojis.map((emoji, i) => (
          <motion.button
            key={`${emoji}-${i}`}
            whileTap={{ scale: 0.8 }}
            onClick={() => onSelect(emoji)}
            className={`text-2xl p-1.5 rounded-lg transition ${
              selected === emoji
                ? 'bg-pink-100 ring-2 ring-pink-400'
                : 'hover:bg-gray-100 active:bg-gray-200'
            }`}
          >
            {emoji}
          </motion.button>
        ))}
      </div>
    </div>
  );
}
